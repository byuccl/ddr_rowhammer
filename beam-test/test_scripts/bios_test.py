def pty2crossover(wb, m, stop):
    ''' Run as a thread '''
    while not stop.is_set():
        r = os.read(m, 1)
        wb.regs.uart_xover_rxtx.write(ord(r))


def crossover2pty(wb, m, stop):
    ''' Run as a thread '''
    while not stop.is_set():
        if wb.regs.uart_xover_rxempty.read() == 0:
            r = wb.regs.uart_xover_rxtx.read()
            os.write(m, bytes(chr(r).encode("utf-8")))

def create_base_filename_identifier(prefix):
    ''' Create a base filename used for all files generated by this experiment '''
    current_date_time = datetime.now().strftime("%B_%d_%Y__%H_%M_%S")
    # Add CTRL as the prefix to specify it is a DDR controller test
    #  (the bistream is not enough - the same bitstream may be used for the DDR test)
    return str(prefix +  "_" + current_date_time)

def setup_logger(log_filename:str, include_level = True, print_stdout = False):
    ''' Static method for creating custom loggers '''
    if include_level:
        formatter = logging.Formatter('[%(asctime)s] %(levelname)-8s %(message)s', datefmt=TIME_STRING_FORMAT)
    else:
        formatter = logging.Formatter('[%(asctime)s] %(message)s', datefmt=TIME_STRING_FORMAT)
    try:
        handler = logging.FileHandler(log_filename)
    except (FileNotFoundError) as error:
        print("Logging File "+log_filename+"cannot be opened")
        return None

    handler.setFormatter(formatter)
    logger = logging.getLogger("main_log")
    logger.setLevel(logging.INFO)
    logger.addHandler(handler)

    if print_stdout:
        consoleHandler = logging.StreamHandler(sys.stdout)
        consoleHandler.setFormatter(formatter)
        logger.addHandler(consoleHandler)

    return logger

def create_log_path(prefix,basename,path_dir=None,prefix_first=False):
    ''' Creates a Path to a log file'''

    if prefix_first:
        filename = str(prefix+"_"+basename+".log")
    else:
        filename = str(basename+"_"+prefix+".log")

    if path_dir:
        filepath = Path(path_dir , filename)
    else:
        filepath = filename
    return filepath

def expect_prompt(expect, number_of_enters=1,expect_timeout=DEFAULT_LITEX_LOGIN_DELAY):
    ''' Send "Enter" and expects the "litex" prompt (does this once)
        Does NOT set state (state actions should set state)
        Returns True if expect was successful, False otherwise
          Calling functions should query for details about failed expect
    '''

    LITEX_LOGIN_PATTERN = "^.*litex[^>]*> "
    for i in range(number_of_enters):
        expect.sendline("\n")
    expect.expect(LITEX_LOGIN_PATTERN,timeout=expect_timeout)
    if expect.has_error():
        return False
    return True

def retry_expect_prompt(ex, number_of_enters=1,expect_retries = 0, expect_timeout=DEFAULT_LITEX_LOGIN_DELAY):
    MAX_TRIES = expect_retries + 1
    success = False
    try_num = 0
    while not success:
        ex.logger.info(f"Expect prompt attempt #{try_num+1}")
        expect_result = expect_prompt(ex.expect,number_of_enters=number_of_enters)
        if not expect_result:
            if try_num >= MAX_TRIES:
                ex.logger.error("Maximum number of tries: exiting")
                return False
            time.sleep(15)
            try_num += 1
        else:
            success = True
    ex.logger.info("Login prompt success")
    return True

