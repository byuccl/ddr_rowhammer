def create_client_state_actions(ex):
    '''
    '''
    wb = RemoteClient()
    wb.open()

    # Need to figure out how to get read_ident working
    #ex.logger.info("Board info:", read_ident(wb))

    m, s = pty.openpty()
    tty = os.ttyname(s)
    ex.logger.info("LiteX Crossover UART created: {}".format(tty))

    stop_event = threading.Event()
    threads = [
        threading.Thread(target=pty2crossover, args=[wb, m, stop_event], daemon=True),
        threading.Thread(target=crossover2pty, args=[wb, m, stop_event], daemon=True),
    ]
    for thread in threads:
        thread.start()

    baudrate = int(float(ex.args.baudrate))
    timout = 30
    #print('Using serial backend: {} with baudrate {}'.format(args.term,baudrate))
    ex.logger.info("Attempting to open:"+str(tty)+" at baud "+str(baudrate)+
            " with timeout=" + str(timout))

    try:
        serial_fd = Serial(tty, baudrate=baudrate, timeout=timout)
    except (Exception) as error:
        # SerialException if device cannot be found or properly configured
        # ValueError if values are incorrect
        ex.logger.error("Failed to open:"+str(tty)+" ("+str(type(error))+":"+str(error)+")")
        return TERMINATING_STATE
    ex.logger.info("Serial port "+tty+" open")

    ex.serial_fd = serial_fd

    ex.expect = serial_expect(serial_fd,ex.logger,pexpect_stdout=ex.uart_log_file, timestampformat = TIME_STRING_FORMAT)
    ex.expect.create_uart_spawn()

    return INITIAL_PROMPT_STATE

def initial_prompt_state_actions(ex):
    ''' Wait for the initial prompt
    '''
    # System has to boot up and calibrate the memory
    boot_time = 30
    send_result = ex.expect.sendline()
    ex.logger.info(f"Giving time for bios to initialize ({boot_time} seconds)")
    time.sleep(boot_time)

    MAX_TRIES = 10
    success = False
    try_num = 0
    while not success:
        ex.logger.info(f"Initial prompt attempt #{try_num+1}")
        expect_result = expect_prompt(ex.expect,number_of_enters=2)
        if not expect_result:
            if try_num >= MAX_TRIES:
                ex.logger.error("Maximum number of tries: exiting")
                return TERMINATING_STATE
            time.sleep(15)
            try_num += 1
        else:
            success = True
    ex.logger.info("Login prompt success")

    return MEM_INIT_STATE

def mem_init_state_actions(ex):
    # Run the memory initialize command
    #mem_init_cmd = f"mem_write 0x40000000 0xa5a5a5a5 0x10000000 4"
    mem_init_cmd = f"mem_write 0x40000000 {ex.args.default_bist_pattern} 0x10000000 4"
    #mem_init_cmd = f"mem_write 0x40000000 {ex.args.default_bist_pattern} 0x100 4"
    #print(mem_init_cmd)
    if ex.args.skip_mem_init:
        ex.logger.info("Skipping memory initialization")
        return MEM_COMPARE_STATE

    send_result = ex.expect.sendline(mem_init_cmd)
    mem_init_delay_time = 90
    ex.logger.info(f"Giving time for mem_write command ({mem_init_delay_time} seconds)")
    time.sleep(mem_init_delay_time)
 
    expect_result = expect_prompt(ex.expect,number_of_enters=2)
    if not expect_result:
        ex.logger.info("No response")
        return TERMINATING_STATE

    return MEM_COMPARE_STATE

def mem_compare_state_actions(ex):
    # Compare memory (takes about 2 minutes): perhaps break this up a bit so we don't have 
    #  the UART full with all the differences when there is a failure
    #mem_cmp 0x40000000 0x60000000 0x08000000
    # There are 0x40000000 bytes or 0x10000000 words
    # If we compare half the array to each other then only 
    # compare 0x08000000 words
    INIT_ADDR =          0x40000000
    COMPARE_ADDR =       0x60000000
    COMPARE_DIFF = COMPARE_ADDR - INIT_ADDR
    COMPARE_INCREMENT =     0x40000
    WORDS_TO_COMPARE =     COMPARE_INCREMENT // 4
    MAX_COMPARE =        0x08000000
    COMPARE_INFO_MESSAGE_LENGTH = 0x800000
    INTER_COMPARE_DELAY = 1.0

    total_increment = 0
    for addr in range(INIT_ADDR,COMPARE_ADDR,COMPARE_INCREMENT):
        compare_addr = addr + COMPARE_DIFF
        total_increment += COMPARE_INCREMENT
        mem_compare_cmd = f"mem_cmp 0x{addr:08X} 0x{compare_addr:08X} 0x{WORDS_TO_COMPARE:08X} 4"
        if total_increment % COMPARE_INFO_MESSAGE_LENGTH == 0:
            ex.logger.info(mem_compare_cmd)
        send_result = ex.expect.sendline(mem_compare_cmd)
        time.sleep(INTER_COMPARE_DELAY)
         #print(send_result)
        expect_result = False
        max_tries = 20
        tries = 0
        while not expect_result:
            expect_result = expect_prompt(ex.expect,number_of_enters=1)
            if not expect_result:
                tries += 1
                ex.logger.info(f"Failed expect prompt try {tries}")
                if tries >= max_tries:
                    return TERMINATING_STATE

    return MEM_COMPARE_STATE

def terminating_state_actions(ex):
    ''' Terminates experiment
        no state change
    '''
    ex.stop()
    return TERMINATING_STATE

def build_experiment(args,logger,single_step=False):
    '''
    Builds the experiment object and its related states for the experiment state machine.
    '''


    # Create a new experiment object
    experiment = NewExperiment(logger,single_step=single_step)

    # Save the arguments
    experiment.args = args
    experiment.logger = logger

    # INITIAL_STARTING_STATE
    # - Do nothing: place holder for start
    experiment.add_state(ExperimentState(
        INITIAL_STARTING_STATE,
        initial_starting_state_actions,
    ))

    experiment.add_state(ExperimentState(
        REPOWER_BOARD_STATE,
        repower_board_state_actions,
    ))

    experiment.add_state(ExperimentState(
        START_SERVER_STATE,
        start_server_state_actions,
    ))

    experiment.add_state(ExperimentState(
        CREATE_CLIENT_STATE,
        create_client_state_actions,
    ))

    experiment.add_state(ExperimentState(
        INITIAL_PROMPT_STATE,
        initial_prompt_state_actions,
    ))

    experiment.add_state(ExperimentState(
        MEM_INIT_STATE,
        mem_init_state_actions,
    ))

    experiment.add_state(ExperimentState(
        MEM_COMPARE_STATE,
        mem_compare_state_actions,
    ))

    # TERMINATING_STATE
    # - Do nothing: place holder for ending state. Will set experiment to "stop"
    # - Enter this state when the experiment cannot continue
    experiment.add_state(ExperimentState(
        TERMINATING_STATE,
        terminating_state_actions,
    ))
    return experiment

